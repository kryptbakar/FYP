"""Fusion dedup evaluation — false-merge and missed-merge rates on a labeled sample.

The fusion engine (fusion.py) groups findings by producer-stamped `dedup_key`.
That is a *heuristic*, so it must be measured, not asserted. This harness scores it
against a human-labeled sample (ml/tests/fixtures/fusion_labeled.json) where every
finding carries `truth_cluster` — the ground-truth "same underlying issue" group.

Scoring is standard pairwise clustering evaluation:
  - a PAIR of findings is "predicted together" if fusion puts them in one cluster,
    and "truly together" if they share a truth_cluster;
  - pairwise precision  = truly-together / predicted-together
      -> FALSE-MERGE RATE = 1 - precision (distinct issues glued together)
  - pairwise recall     = predicted-together / truly-together
      -> MISSED-MERGE RATE = 1 - recall (one issue left fragmented)
  - F1 combines both.

The bundled sample deliberately contains known failure modes (unstamped keys,
inconsistent path normalization, over-coarse rule keys, cross-domain campaign
links) so the measured rates are meaningful. Extend the fixture with rows labeled
from a live pilot to re-score on real data — the harness is unchanged.

Usage:
    python eval_fusion.py [--fixture path.json] [--out reports/]
"""
from __future__ import annotations

import argparse
import json
import logging
from datetime import datetime, timezone
from itertools import combinations
from pathlib import Path

from fusion import build_clusters

log = logging.getLogger("ml.eval_fusion")

DEFAULT_FIXTURE = Path(__file__).parent / "tests" / "fixtures" / "fusion_labeled.json"


def pairwise_sets(assignment: dict[int, str]) -> set[tuple[int, int]]:
    """All unordered id-pairs that share a cluster label."""
    by_label: dict[str, list[int]] = {}
    for fid, label in assignment.items():
        by_label.setdefault(label, []).append(fid)
    pairs: set[tuple[int, int]] = set()
    for members in by_label.values():
        pairs.update(tuple(sorted(p)) for p in combinations(members, 2))
    return pairs


def score(findings: list[dict]) -> dict:
    consensus = build_clusters(findings)
    # Predicted cluster id: the frozen member list uniquely identifies a cluster.
    predicted = {f["id"]: ",".join(map(str, consensus[f["id"]]["members"])) for f in findings}
    truth = {f["id"]: f["truth_cluster"] for f in findings}

    pred_pairs = pairwise_sets(predicted)
    true_pairs = pairwise_sets(truth)
    tp = pred_pairs & true_pairs

    precision = len(tp) / len(pred_pairs) if pred_pairs else 1.0
    recall = len(tp) / len(true_pairs) if true_pairs else 1.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0

    false_merges = sorted(pred_pairs - true_pairs)
    missed_merges = sorted(true_pairs - pred_pairs)
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "n_findings": len(findings),
        "n_predicted_pairs": len(pred_pairs),
        "n_true_pairs": len(true_pairs),
        "pairwise_precision": round(precision, 4),
        "pairwise_recall": round(recall, 4),
        "pairwise_f1": round(f1, 4),
        "false_merge_rate": round(1 - precision, 4),
        "missed_merge_rate": round(1 - recall, 4),
        "false_merge_pairs": false_merges,
        "missed_merge_pairs": missed_merges,
    }


def to_markdown(r: dict, findings: list[dict]) -> str:
    note = {f["id"]: f.get("note", "") for f in findings}

    def pair_rows(pairs):
        if not pairs:
            return ["_none_"]
        return [f"- ({a}, {b}) — {note.get(a) or note.get(b) or 'no note'}" for a, b in pairs]

    return "\n".join([
        "# Fusion dedup evaluation report",
        "",
        f"_Auto-generated by `ml/eval_fusion.py` on {r['generated_at']} against a "
        f"labeled sample of {r['n_findings']} findings. Re-run the harness after "
        "extending the fixture with pilot-labeled rows._",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Pairwise precision | {r['pairwise_precision']:.3f} |",
        f"| Pairwise recall | {r['pairwise_recall']:.3f} |",
        f"| Pairwise F1 | {r['pairwise_f1']:.3f} |",
        f"| **False-merge rate** (distinct issues glued) | {r['false_merge_rate'] * 100:.1f}% |",
        f"| **Missed-merge rate** (one issue fragmented) | {r['missed_merge_rate'] * 100:.1f}% |",
        "",
        "## False merges (over-coarse keys)",
        *pair_rows(r["false_merge_pairs"]),
        "",
        "## Missed merges (unstamped / inconsistent keys)",
        *pair_rows(r["missed_merge_pairs"]),
        "",
        "## Interpretation",
        "",
        "False merges are the dangerous direction (an analyst dismisses two issues as "
        "one), so key rules are tuned precision-first; missed merges only forfeit a "
        "consensus boost. Each listed pair is an actionable key-rule fix: normalize "
        "paths before keying, stamp keys in every bridge, and split over-coarse "
        "rule-family keys by rule id (see ml/FUSION.md key rules).",
    ]) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fixture", type=Path, default=DEFAULT_FIXTURE)
    ap.add_argument("--out", type=Path, default=Path("reports"))
    args = ap.parse_args()

    findings = json.loads(args.fixture.read_text())["findings"]
    report = score(findings)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "fusion_evaluation.json").write_text(json.dumps(report, indent=2))
    (args.out / "fusion_evaluation.md").write_text(to_markdown(report, findings))
    log.info("wrote %s and %s", args.out / "fusion_evaluation.json", args.out / "fusion_evaluation.md")
    print(to_markdown(report, findings))


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s %(message)s")
    main()
